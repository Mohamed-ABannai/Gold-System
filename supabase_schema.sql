create view public.sales_ledger as
select
  s.id as sale_id,
  s.invoice_number,
  s.customer_name,
  s.customer_phone,
  s.customer_email,
  s.customer_country_code,
  s.customer_personal_id,
  s.customer_address,
  s.payment_method,
  s.discount,
  s.total,
  s.created_at,
  coalesce(
    string_agg(
      concat_ws(' ', si.name, nullif(si.product_type, ''), 'عيار ' || si.karat::text, si.weight::text || 'g', si.quantity::text || 'x'),
      ' | '
      order by si.id
    ),
    ''
  ) as products_summary,
  lower(
    concat_ws(
      ' ',
      s.invoice_number,
      s.customer_name,
      s.customer_phone,
      s.customer_email,
      coalesce(string_agg(si.name || ' ' || si.product_type, ' '), '')
    )
  ) as search_text
from public.sales s
left join public.sale_items si on si.sale_id = s.id
group by s.id;

create view public.sold_items_ledger as
select
  s.invoice_number,
  s.customer_name,
  s.created_at,
  si.name,
  si.product_type,
  si.karat,
  si.weight,
  si.quantity,
  si.discount,
  si.total
from public.sale_items si
join public.sales s on s.id = si.sale_id;

