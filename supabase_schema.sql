create extension if not exists pgcrypto;

create or replace function public.set_updated_at()
returns trigger
language plpgsql
as $$
begin
  new.updated_at = now();
  return new;
end;
$$;

create table if not exists public.users (
  id bigint generated by default as identity primary key,
  username text not null unique,
  password_hash text not null,
  full_name text not null,
  role text not null default 'employee',
  created_at timestamptz not null default now()
);

-- Automatically hash plain text passwords on insert or update
create or replace function public.hash_user_password()
returns trigger
language plpgsql
security definer
as $$
begin
  if new.password_hash is not null and new.password_hash !~ '^[a-fA-F0-9]{64}$' then
    new.password_hash = encode(digest(new.password_hash, 'sha256'), 'hex');
  end if;
  return new;
end;
$$;

drop trigger if exists hash_user_password_trigger on public.users;
create trigger hash_user_password_trigger
before insert or update of password_hash on public.users
for each row execute function public.hash_user_password();


create table if not exists public.store_settings (
  id bigint primary key default 1 check (id = 1),
  store_name text not null default 'محل الذهب',
  tax_number text not null default '',
  phone text not null default '',
  address text not null default '',
  logo_path text,
  stamp_path text,
  updated_at timestamptz not null default now()
);

create table if not exists public.gold_prices (
  id bigint generated by default as identity primary key,
  karat integer not null unique check (karat in (18, 21, 22, 24)),
  buy_price_per_gram numeric(12, 3) not null default 0,
  margin_percent numeric(8, 3) not null default 5,
  updated_at timestamptz not null default now()
);

create table if not exists public.products (
  id bigint generated by default as identity primary key,
  name text not null,
  product_type text not null default '',
  karat integer not null check (karat in (18, 21, 22, 24)),
  weight numeric(12, 3) not null check (weight > 0),
  quantity integer not null default 1 check (quantity > 0),
  image_path text,
  image_url text,
  status text not null default 'available' check (status in ('available', 'sold')),
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table if not exists public.sales (
  id bigint generated by default as identity primary key,
  invoice_number text not null unique,
  customer_name text not null,
  customer_phone text not null default '',
  customer_email text not null default '',
  customer_country_code text not null default '973',
  customer_personal_id text not null default '',
  customer_address text not null default '',
  payment_method text not null default '',
  discount numeric(14, 3) not null default 0,
  total numeric(14, 3) not null default 0,
  user_id bigint references public.users(id) on delete set null,
  created_at timestamptz not null default now()
);

create table if not exists public.sale_items (
  id bigint generated by default as identity primary key,
  sale_id bigint not null references public.sales(id) on delete cascade,
  product_id bigint references public.products(id) on delete set null,
  name text not null,
  product_type text not null default '',
  karat integer not null,
  weight numeric(12, 3) not null default 0,
  quantity integer not null default 1,
  unit_price numeric(12, 3) not null,
  discount numeric(14, 3) not null default 0,
  total numeric(14, 3) not null
);

